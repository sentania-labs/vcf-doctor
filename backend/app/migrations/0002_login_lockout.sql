-- Login lockout counters (#74). Stored in PostgreSQL rather than in each
-- worker's memory so the five-failure per-address threshold and the
-- 30-per-minute deployment ceiling hold across every worker and replica.

CREATE TABLE login_failures (
    ip           TEXT PRIMARY KEY,
    failures     INTEGER NOT NULL,
    last_failure DOUBLE PRECISION NOT NULL,
    updated_seq  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
);
CREATE INDEX ix_login_failures_lru ON login_failures(last_failure, updated_seq);

CREATE TABLE login_failure_window (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX ix_login_failure_window_time ON login_failure_window(occurred_at, id);
